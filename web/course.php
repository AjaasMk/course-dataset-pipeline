<?php
require __DIR__ . '/lib.php';

$index    = load_index();
$segments = $index['segment_order'];
$admin    = is_admin();
$course   = find_course($_GET['course'] ?? '');

if ($course === null) {
    http_response_code(404);
    echo 'Course not found. <a href="index.php">Back to the library</a>.';
    exit;
}
?>
<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title><?= htmlspecialchars($course['name']) ?> | Course Library</title>
  <link rel="stylesheet" href="style.css">
</head>
<body>

<div class="topbar">
  <div class="topbar-inner">
    <span>Career information for students in Grades 8–12 and their parents</span>
    <span><?= $admin ? 'Admin view' : 'Student view' ?></span>
  </div>
</div>

<header class="site-header">
  <div class="header-inner">
    <a class="brand" href="index.php"><span class="brand-mark">C</span> Career Portal</a>
    <div>
      <a class="btn <?= $admin ? '' : 'active' ?>" href="course.php?course=<?= urlencode($course['course_key']) ?>">Student view</a>
      <a class="btn <?= $admin ? 'active' : '' ?>" href="course.php?course=<?= urlencode($course['course_key']) ?>&admin=1">Admin view</a>
    </div>
  </div>
</header>

<section class="hero">
  <div class="hero-card">
    <span class="eyebrow"><?= htmlspecialchars($course['level']) ?></span>
    <span class="eyebrow"><?= htmlspecialchars($course['field']) ?></span>
    <h1><?= htmlspecialchars($course['name']) ?></h1>
    <p>
      This page brings together what is known about the course across fourteen
      standard sections: what you study, how you get in, what it costs and where
      it leads.
    </p>
  </div>
</section>

<div class="page">
  <?php foreach ($segments as $segment): ?>
    <?php
      $state  = segment_state($course, $segment);
      $fields = array_filter($state['fields'] ?? [], fn($v) => $v !== null && $v !== '' && $v !== []);
      $hasContent = (bool) $fields;
    ?>
    <section class="content-section">
      <h2><?= htmlspecialchars($segment) ?></h2>

      <?php if ($admin): ?>
        <p class="sub">
          <?php $p = $state['provenance']; ?>
          <span class="pill <?= $p === 'generated' ? 'generated' : ($p === 'sourced' ? 'sourced' : 'none') ?>">
            <?= htmlspecialchars(str_replace('_', ' ', $p)) ?>
          </span>
          <?php if ($state['sources']): ?>
            from <?= htmlspecialchars(implode(', ', $state['sources'])) ?>
          <?php endif; ?>
        </p>
      <?php endif; ?>

      <?php if ($hasContent): ?>
        <?php foreach ($fields as $key => $value): ?>
          <div class="field-block">
            <h4><?= htmlspecialchars(humanise($key)) ?></h4>
            <?= render_value($value) ?>
          </div>
        <?php endforeach; ?>
      <?php elseif ($state['provenance'] === 'sourced'): ?>
        <div class="empty-note">
          <?php if ($admin): ?>
            Source documents retrieved, but extraction has not been run for this
            segment yet, so no field values exist. This reports the real state
            rather than implying content is present.
          <?php else: ?>
            Information for this section is being prepared.
          <?php endif; ?>
        </div>
      <?php else: ?>
        <div class="empty-note">
          <?php if ($admin): ?>
            No source document found and nothing generated for this segment.
          <?php else: ?>
            Information for this section is being prepared.
          <?php endif; ?>
        </div>
      <?php endif; ?>

      <?php /* Admin only. Provenance is an internal fact about how content was
               produced; a student is shown the content, never the machinery. */ ?>
      <?php if ($admin && $state['provenance'] === 'generated'): ?>
        <div class="admin-strip">
          Generated by <code><?= htmlspecialchars((string) $state['generator_model']) ?></code>
          on <?= htmlspecialchars(substr((string) $state['generated_at'], 0, 10)) ?>.
          No citation exists for generated content.
          <?php if ($state['sources_attempted']): ?>
            <br>Sources checked and found nothing:
            <?= htmlspecialchars(implode(', ', $state['sources_attempted'])) ?>.
          <?php endif; ?>
          <br>Review required: <?= $state['review_required'] ? 'yes' : 'no' ?> ·
          Publishable: <?= $state['publishable'] ? 'yes' : 'no' ?>
        </div>
      <?php endif; ?>
    </section>
  <?php endforeach; ?>

  <section class="content-section">
    <h2>Page verification area</h2>
    <p class="sub">
      Last reviewed: <?= date('F Y') ?> ·
      Content status: Pilot ·
      Reviewer: Career Content Team
    </p>
  </section>
</div>

<footer>
  <strong>Career Portal Course Library</strong><br>
  Course information should guide exploration and should not replace official
  eligibility, admission or professional-regulation sources.
</footer>

</body>
</html>
