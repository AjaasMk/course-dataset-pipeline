"""Export the pipeline's sqlite state into the prototype MySQL shape.

Emits SQL rather than connecting to a database: the client's MySQL is not ours
to write to, the schema is still provisional (see docs/specs/laravel_schema.sql),
and a file can be reviewed before anything is executed.

Run: PYTHONPATH=. python -m src.persist.mysql_export > data/export.sql
"""

import json
import sqlite3
from pathlib import Path
from typing import Iterable, Optional

from src.courses.taxonomy import load_taxonomy
from src.retrieve.models import RETRIEVAL_SEGMENTS, Segment

GENERATED_DIR = Path("data/generated")
MANIFEST_DB = Path("data/manifest.db")
INSTITUTIONS_DB = Path("data/institutions.db")

SEGMENT_ORDER = [s.value for s in Segment if s in RETRIEVAL_SEGMENTS]


def _quote(value) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return "1" if value else "0"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, (list, dict)):
        value = json.dumps(value, ensure_ascii=False)
    return "'" + str(value).replace("\\", "\\\\").replace("'", "''") + "'"


def _insert(table: str, columns: list[str], rows: Iterable[tuple]) -> list[str]:
    out = []
    batch: list[str] = []
    for row in rows:
        batch.append("(" + ",".join(_quote(v) for v in row) + ")")
        if len(batch) >= 200:
            out.append(f"INSERT INTO {table} ({','.join(columns)}) VALUES\n" + ",\n".join(batch) + ";")
            batch = []
    if batch:
        out.append(f"INSERT INTO {table} ({','.join(columns)}) VALUES\n" + ",\n".join(batch) + ";")
    return out


def _sourced_segments(db_path: Path = MANIFEST_DB) -> dict[str, set[str]]:
    conn = sqlite3.connect(db_path)
    try:
        rows = conn.execute(
            "select distinct i.course_id, i.segment from retrieval_intents i "
            "join intent_resolutions r on i.intent_id = r.intent_id "
            "join documents d on d.document_id = r.document_id "
            "where d.local_path is not null"
        ).fetchall()
    finally:
        conn.close()
    have: dict[str, set[str]] = {}
    for course_id, segment in rows:
        have.setdefault(course_id, set()).add(segment)
    return have


def _generated_records() -> dict[tuple[str, str], dict]:
    out: dict[tuple[str, str], dict] = {}
    if not GENERATED_DIR.exists():
        return out
    for path in GENERATED_DIR.glob("*.json"):
        record = json.loads(path.read_text(encoding="utf-8"))
        out[(record["course_id"], record["segment"])] = record
    return out


def export(limit_courses: Optional[list[str]] = None) -> str:
    statements: list[str] = [
        "-- Generated by src/persist/mysql_export.py against the prototype schema.",
        "-- Review before executing: the schema is provisional pending the client's",
        "-- answer on schema ownership.",
        "SET FOREIGN_KEY_CHECKS = 0;",
    ]

    courses = load_taxonomy()
    if limit_courses:
        wanted = set(limit_courses)
        courses = [c for c in courses if c.course_id in wanted]

    statements += _insert(
        "courses",
        ["course_key", "standard_course_name", "field_of_study", "qualification_level"],
        (
            (c.course_id, c.standard_course_name, c.fields[0] if c.fields else None, "Undergraduate")
            for c in courses
        ),
    )

    sourced = _sourced_segments()
    generated = _generated_records()

    # Always 14 rows per course. A segment with nothing behind it is recorded
    # as no_source_found rather than omitted: an absent row and an explicit
    # "we looked and found nothing" are different claims, and only one of them
    # is auditable.
    segment_rows = []
    field_rows = []
    for course in courses:
        for segment in SEGMENT_ORDER:
            record = generated.get((course.course_id, segment))
            if record:
                segment_rows.append(
                    (
                        course.course_id, segment, "generated", 1,
                        1 if record.get("publishable") else 0,
                        record.get("generator_model"), record.get("generated_at"),
                    )
                )
                for key, value in (record.get("fields") or {}).items():
                    if value in (None, "", [], {}):
                        continue
                    is_list = isinstance(value, (list, dict))
                    field_rows.append(
                        (
                            course.course_id, segment, key, None,
                            None if is_list else str(value),
                            value if is_list else None,
                            1,
                        )
                    )
            elif segment in sourced.get(course.course_id, set()):
                # Sourced segments have documents but no extracted field values
                # yet -- extraction has not been run at scale, so the row is
                # created without fields rather than pretending they exist.
                segment_rows.append((course.course_id, segment, "sourced", 1, 0, None, None))
            else:
                segment_rows.append((course.course_id, segment, "no_source_found", 1, 0, None, None))

    statements.append(
        "-- course_segments uses course_key here; the loader resolves it to courses.id."
    )
    statements += _insert(
        "course_segments",
        ["course_key", "segment", "provenance", "review_required", "publishable",
         "generator_model", "generated_at"],
        segment_rows,
    )
    statements += _insert(
        "segment_fields",
        ["course_key", "segment", "field_key", "field_id", "value_text", "value_json",
         "is_generated"],
        field_rows,
    )

    statements.append("SET FOREIGN_KEY_CHECKS = 1;")
    return "\n\n".join(statements)


def summary(limit_courses: Optional[list[str]] = None) -> dict:
    courses = load_taxonomy()
    if limit_courses:
        wanted = set(limit_courses)
        courses = [c for c in courses if c.course_id in wanted]
    sourced = _sourced_segments()
    generated = _generated_records()
    counts = {"sourced": 0, "generated": 0, "no_source_found": 0}
    for course in courses:
        for segment in SEGMENT_ORDER:
            if (course.course_id, segment) in generated:
                counts["generated"] += 1
            elif segment in sourced.get(course.course_id, set()):
                counts["sourced"] += 1
            else:
                counts["no_source_found"] += 1
    return {"courses": len(courses), "cells": len(courses) * len(SEGMENT_ORDER), **counts}


if __name__ == "__main__":
    print(export())
