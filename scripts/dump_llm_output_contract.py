"""Emit the exact JSON shape each LLM call must return.

Run: PYTHONPATH=. python scripts/dump_llm_output_contract.py [--segment Fees]

Not a description of the contract -- the contract itself. Extraction shapes are
taken from the same model_json_schema() call that facts_extraction.py
interpolates into its system prompt, so this file cannot describe something
other than what is actually sent. Generation shapes come from the same
SEGMENT_SCHEMAS the generation prompt uses.

Writes docs/specs/llm-output-contract.json.
"""

import argparse
import json
import sys
from pathlib import Path

from pydantic import Field, create_model

from src.extract.block_schemas import ADVISORY_BLOCK_SCHEMAS
from src.extract.facts_extraction import (
    _Citation,
    _CourseExtraction,
    _CurriculumExtraction,
    _EligibilityExtraction,
    _entry_model_for,
    _SpecialisationExtraction,
)
from src.extract.segment_schemas import SEGMENT_SCHEMAS
from src.facts.segment_facts import SEGMENT_FACTS

OUT = Path("docs/specs/llm-output-contract.json")

SINGLE = {
    "Curriculum": _CurriculumExtraction,
    "Eligibility": _EligibilityExtraction,
    "Course Identity + Duration & Mode": _CourseExtraction,
}
LISTY = {"Specialisation": _SpecialisationExtraction}


def example_for(schema: dict) -> dict:
    """A filled-in instance, because a JSON Schema is hard to eyeball.

    Values name their own type rather than pretending to be data -- a fake
    "Rs 45,000" in a contract document is the kind of thing that ends up
    quoted back as if it were a real figure.
    """
    out = {}
    for name, spec in (schema.get("properties") or {}).items():
        kind = spec.get("type")
        if kind == "array":
            out[name] = ["<string>"]
        elif kind == "integer":
            out[name] = 0
        elif kind == "boolean":
            out[name] = True
        elif kind == "object":
            out[name] = {}
        else:
            out[name] = "<string or null>"
    return out


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--segment", default=None)
    args = parser.parse_args()

    citation = _Citation.model_json_schema()
    contract = {
        "note": "generated by scripts/dump_llm_output_contract.py from the live models",
        "citation_entry": {
            "shape": example_for(citation),
            "rule": "one entry per POPULATED field. A populated field with no "
                    "citation is nulled before storage (Hard Constraint 2/4).",
        },
        "extraction": {},
        "generation": {},
        "advisory_blocks": {},
    }

    for name, model in SINGLE.items():
        schema = model.model_json_schema()
        contract["extraction"][name] = {
            "cardinality": "one record per course",
            "response": {**example_for(schema), "citations": [example_for(citation)]},
        }

    for name, model in LISTY.items():
        contract["extraction"][name] = {
            "cardinality": "many records per course",
            "response": {"specialisations": [
                {**example_for(model.model_fields["specialisations"].annotation.__args__[0]
                               .model_json_schema()),
                 "citations": [example_for(citation)]}
            ]},
        }

    for segment, (fact_model, _) in SEGMENT_FACTS.items():
        entry = _entry_model_for(fact_model, "E")
        wrapper = create_model("W", entries=(list[entry], Field(default_factory=list)))
        shape = example_for(entry.model_json_schema())
        shape.pop("citations", None)
        contract["extraction"][segment] = {
            "cardinality": "many records per course",
            "model": fact_model.__name__,
            "response": {"entries": [{**shape, "citations": [example_for(citation)]}]},
        }

    for segment, schema in SEGMENT_SCHEMAS.items():
        contract["generation"][segment] = {
            "response": schema,
            "rule": "no citations -- generated content has no source to cite",
        }

    for block, schema in ADVISORY_BLOCK_SCHEMAS.items():
        contract["advisory_blocks"][block] = {"response": schema}

    OUT.write_text(json.dumps(contract, indent=1, ensure_ascii=False), encoding="utf-8")

    if args.segment:
        print(json.dumps(contract["extraction"].get(args.segment)
                         or contract["generation"].get(args.segment), indent=1))
        return 0

    print("EXTRACTION -- returns cited values, one citation per populated field\n")
    for name, entry in contract["extraction"].items():
        response = entry["response"]
        # The wrapper key differs per segment ("entries", "specialisations"),
        # and a single-record segment has no wrapper at all.
        listed = next(
            (v for k, v in response.items()
             if k != "citations" and isinstance(v, list) and v and isinstance(v[0], dict)),
            None,
        )
        fields = listed[0] if listed else response
        count = len([k for k in fields if k != "citations"])
        print(f"  {name:<36}{count:>3} fields   {entry['cardinality']}")

    print("\nGENERATION -- returns values with no citations, where nothing was found\n")
    for name, entry in contract["generation"].items():
        print(f"  {name:<36}{len(entry['response']):>3} fields")

    print("\nADVISORY BLOCKS -- no source exists for these, ever\n")
    for name, entry in contract["advisory_blocks"].items():
        print(f"  {name:<36}{len(entry['response']):>3} fields")

    print(f"\n-> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
